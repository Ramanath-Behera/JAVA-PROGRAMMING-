package JAVA_one.Methods;

public class BuiltIn {
    public static void main(String[] args) {

        // MATHS Methods
        System.out.println(Math.sqrt(65));
        System.out.println(Math.cbrt(6788));
        System.out.println(Math.PI); // variable of Math class not method
        System.out.println(Math.abs(-48784)); //converts -ve to +ve
        System.out.println(Math.floor(6.8));  // returns GIF value (also called floor)
        System.out.println(Math.min(4,5));    // returns smallest value of 2
        System.out.println(Math.max(4,5));    // returns largest value of 2

        System.out.println(Math.pow(45,5)); // can include float values BUT for a^b if a is -ve then b must be integer(+,-)
        // ERROR : O^0 != 1 = NaN



    }
}
